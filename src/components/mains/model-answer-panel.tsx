"use client";

import { Sparkles, Trash2 } from "lucide-react";
import { useState } from "react";
import type { ManagedQuestion } from "@/components/mains/mains-manager";
import { Button } from "@/components/ui/button";
import { Select, Textarea } from "@/components/ui/input";
import { clearModelAnswer, regenerateModelAnswer, setModelAnswer } from "@/lib/actions/mains";

/** Both routes to a model answer: write one, or generate one and edit it.
 *
 *  Generation fills the editor rather than saving straight to the question,
 *  so nothing reaches learners until an admin has read it. A model answer is
 *  the thing candidates measure themselves against — an unreviewed invented
 *  statistic in it teaches the wrong number to everyone who reads it. */
export function ModelAnswerPanel({
  question,
  onDone,
}: {
  question: ManagedQuestion;
  onDone: () => void;
}) {
  const [draft, setDraft] = useState(question.modelAnswer ?? "");
  const [language, setLanguage] = useState<"en" | "hi">(
    question.textHi && !question.textEn ? "hi" : "en",
  );
  const [generating, setGenerating] = useState(false);
  const [saving, setSaving] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [generatedBy, setGeneratedBy] = useState<string | null>(null);

  const words = draft.trim().split(/\s+/).filter(Boolean).length;
  const target = question.wordLimit;

  async function onGenerate() {
    setGenerating(true);
    setError(null);
    const result = await regenerateModelAnswer(question.id, language);
    setGenerating(false);
    if (!result.ok || !result.answer) {
      setError(result.error ?? "Couldn't generate an answer.");
      return;
    }
    setDraft(result.answer);
    setGeneratedBy(result.model ?? null);
  }

  async function onSave() {
    setSaving(true);
    setError(null);
    const result = await setModelAnswer(question.id, draft);
    setSaving(false);
    if (!result.ok) {
      setError(result.error ?? "Couldn't save that answer.");
      return;
    }
    onDone();
  }

  async function onClear() {
    setSaving(true);
    setError(null);
    const result = await clearModelAnswer(question.id);
    setSaving(false);
    if (!result.ok) {
      setError(result.error ?? "Couldn't clear that answer.");
      return;
    }
    onDone();
  }

  return (
    <div className="space-y-4">
      <div className="rounded-lg border border-line bg-raised/40 p-3">
        <p className="text-sm leading-relaxed text-ink">
          {question.textEn ?? question.textHi}
        </p>
        <p className="mt-1.5 text-xs text-muted">
          {question.paper}
          {question.section ? ` · Sec ${question.section}` : ""} · {question.marks} marks
          {target ? ` · target ~${target} words` : ""}
          {question.biharAngle ? " · Bihar angle" : ""}
        </p>
      </div>

      <div className="flex flex-wrap items-end gap-2">
        <label className="flex-1 sm:max-w-40">
          <span className="mb-1.5 block text-sm font-medium text-ink">Language</span>
          <Select
            value={language}
            onChange={(e) => setLanguage(e.target.value as "en" | "hi")}
            aria-label="Answer language"
          >
            <option value="en">English</option>
            <option value="hi">Hindi</option>
          </Select>
        </label>
        <Button variant="secondary" onClick={() => void onGenerate()} loading={generating}>
          <Sparkles className="size-4" aria-hidden />
          {draft ? "Regenerate" : "Generate with AI"}
        </Button>
      </div>

      <div>
        <label className="mb-1.5 block text-sm font-medium text-ink" htmlFor="model-answer">
          Model answer
        </label>
        <Textarea
          id="model-answer"
          rows={16}
          value={draft}
          onChange={(e) => setDraft(e.target.value)}
          placeholder="Write the answer yourself, or generate one and edit it here."
          className="font-mono text-xs leading-relaxed"
        />
        <p className="mt-1.5 flex flex-wrap items-center gap-x-3 text-xs text-muted tabular-nums">
          <span>
            {words} words
            {target ? ` · ${Math.round((words / target) * 100)}% of target` : ""}
          </span>
          {generatedBy && <span className="text-faint">generated by {generatedBy}</span>}
          {!generatedBy && question.modelAnswer && (
            <span className="text-faint">
              currently {question.modelAnswerIsAi ? "AI-generated" : "written by you"}
            </span>
          )}
        </p>
      </div>

      {generatedBy && (
        <p className="rounded-lg border border-warn/40 bg-warn-soft px-3.5 py-2.5 text-xs leading-relaxed text-ink">
          Read it before saving. Candidates measure themselves against this answer, so a figure
          the model invented becomes a wrong number memorised by everyone who studies it. Check
          any statistic, committee name or case citation first.
        </p>
      )}

      {error && <p className="text-sm text-danger">{error}</p>}

      <div className="flex flex-wrap justify-end gap-2">
        {question.modelAnswer && (
          <Button variant="dangerOutline" onClick={() => void onClear()} loading={saving}>
            <Trash2 className="size-4" aria-hidden /> Remove
          </Button>
        )}
        <Button onClick={() => void onSave()} loading={saving} disabled={draft.trim().length < 40}>
          Save answer
        </Button>
      </div>
    </div>
  );
}
